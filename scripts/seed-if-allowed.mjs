/**
 * ビルド時に seed を「明示的に許可されたときだけ」実行する。
 *
 * -----------------------------------------------------------------------------
 * なぜビルド時に走らせるのか
 * -----------------------------------------------------------------------------
 * Vercel は Marketplace 統合（Supabase / Upstash）が注入した秘密を **CLI に一切渡さない**。
 * `vercel env pull` も `vercel env run` も統合由来の変数は空文字で返り、ダッシュボードでも
 * Sensitive として伏せられる。したがって手元から `pnpm db:seed` を流す手段が無い。
 * ビルド環境には正しく注入されるので、そこで実行する。
 *
 * -----------------------------------------------------------------------------
 * なぜ無条件に走らせないのか
 * -----------------------------------------------------------------------------
 * `prisma/seed.ts` は**マスタ系を全削除してから再投入する**（Application / LicensePhoto /
 * UploadToken は保持）。無条件にすると、**管理画面で作成したお知らせがデプロイのたびに消える。**
 * そのため `ALLOW_PROD_SEED=1` のときだけ実行し、投入が済んだらその変数を削除する運用にする。
 * この変数は `lib/seed-guard.ts` が本番 seed のオプトインとして既に使っているものと同じで、
 * 新しい抜け道を増やしていない（SEC-012）。
 *
 * -----------------------------------------------------------------------------
 * 失敗の扱い
 * -----------------------------------------------------------------------------
 * **許可されているのに失敗したらビルドを落とす。** `|| true` で握り潰すと、
 * 「seed したつもりでデータが入っていない」状態のままデプロイが成功してしまう。
 * 許可されていない場合だけ、何もせず正常終了する。
 */

import { spawnSync } from 'node:child_process'

if (process.env.ALLOW_PROD_SEED !== '1') {
  console.log('[seed] ALLOW_PROD_SEED=1 が無いので seed をスキップします。')
  process.exit(0)
}

console.log('[seed] ALLOW_PROD_SEED=1 を検出。seed を実行します。')
const result = spawnSync('pnpm', ['db:seed'], { stdio: 'inherit', env: process.env })

if (result.error) {
  console.error('[seed] 実行できませんでした:', result.error.message)
  process.exit(1)
}
process.exit(result.status ?? 1)
